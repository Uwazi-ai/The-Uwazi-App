
-- Add full address fields to profiles
ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS address_line1 text,
  ADD COLUMN IF NOT EXISTS address_line2 text,
  ADD COLUMN IF NOT EXISTS city text,
  ADD COLUMN IF NOT EXISTS state_code text,
  ADD COLUMN IF NOT EXISTS full_address text;

-- Helper function: derive state from ZIP
CREATE OR REPLACE FUNCTION public.get_state_from_zip(zip text)
RETURNS text
LANGUAGE plpgsql
STABLE
SET search_path = 'public'
AS $$
BEGIN
  RETURN CASE
    WHEN zip BETWEEN '35000' AND '36999' THEN 'AL'
    WHEN zip BETWEEN '99500' AND '99999' THEN 'AK'
    WHEN zip BETWEEN '85000' AND '86999' THEN 'AZ'
    WHEN zip BETWEEN '71600' AND '72999' THEN 'AR'
    WHEN zip BETWEEN '90000' AND '96699' THEN 'CA'
    WHEN zip BETWEEN '80000' AND '81999' THEN 'CO'
    WHEN zip BETWEEN '06000' AND '06999' THEN 'CT'
    WHEN zip BETWEEN '19700' AND '19999' THEN 'DE'
    WHEN zip BETWEEN '32000' AND '34999' THEN 'FL'
    WHEN zip BETWEEN '30000' AND '31999' THEN 'GA'
    WHEN zip BETWEEN '96700' AND '96999' THEN 'HI'
    WHEN zip BETWEEN '83200' AND '83999' THEN 'ID'
    WHEN zip BETWEEN '60000' AND '62999' THEN 'IL'
    WHEN zip BETWEEN '46000' AND '47999' THEN 'IN'
    WHEN zip BETWEEN '50000' AND '52999' THEN 'IA'
    WHEN zip BETWEEN '66000' AND '67999' THEN 'KS'
    WHEN zip BETWEEN '40000' AND '42999' THEN 'KY'
    WHEN zip BETWEEN '70000' AND '71499' THEN 'LA'
    WHEN zip BETWEEN '03900' AND '04999' THEN 'ME'
    WHEN zip BETWEEN '20600' AND '21999' THEN 'MD'
    WHEN zip BETWEEN '01000' AND '02799' THEN 'MA'
    WHEN zip BETWEEN '48000' AND '49999' THEN 'MI'
    WHEN zip BETWEEN '55000' AND '56799' THEN 'MN'
    WHEN zip BETWEEN '38600' AND '39999' THEN 'MS'
    WHEN zip BETWEEN '63000' AND '65999' THEN 'MO'
    WHEN zip BETWEEN '59000' AND '59999' THEN 'MT'
    WHEN zip BETWEEN '68000' AND '69999' THEN 'NE'
    WHEN zip BETWEEN '88900' AND '89999' THEN 'NV'
    WHEN zip BETWEEN '03000' AND '03899' THEN 'NH'
    WHEN zip BETWEEN '07000' AND '08999' THEN 'NJ'
    WHEN zip BETWEEN '87000' AND '88499' THEN 'NM'
    WHEN zip BETWEEN '10000' AND '14999' THEN 'NY'
    WHEN zip BETWEEN '27000' AND '28999' THEN 'NC'
    WHEN zip BETWEEN '58000' AND '58999' THEN 'ND'
    WHEN zip BETWEEN '43000' AND '45999' THEN 'OH'
    WHEN zip BETWEEN '73000' AND '74999' THEN 'OK'
    WHEN zip BETWEEN '97000' AND '97999' THEN 'OR'
    WHEN zip BETWEEN '15000' AND '19699' THEN 'PA'
    WHEN zip BETWEEN '02800' AND '02999' THEN 'RI'
    WHEN zip BETWEEN '29000' AND '29999' THEN 'SC'
    WHEN zip BETWEEN '57000' AND '57999' THEN 'SD'
    WHEN zip BETWEEN '37000' AND '38599' THEN 'TN'
    WHEN zip BETWEEN '75000' AND '79999' THEN 'TX'
    WHEN zip BETWEEN '84000' AND '84999' THEN 'UT'
    WHEN zip BETWEEN '05000' AND '05999' THEN 'VT'
    WHEN zip BETWEEN '20100' AND '20599' THEN 'VA'
    WHEN zip BETWEEN '98000' AND '99499' THEN 'WA'
    WHEN zip BETWEEN '24700' AND '26999' THEN 'WV'
    WHEN zip BETWEEN '53000' AND '54999' THEN 'WI'
    WHEN zip BETWEEN '82000' AND '83199' THEN 'WY'
    WHEN zip BETWEEN '20000' AND '20099' THEN 'DC'
    ELSE 'MO'
  END;
END;
$$;
